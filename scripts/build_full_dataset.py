def parse_line(line):
    m = re.search(r'(R\d{4})', line)
    if not m:
        return None
    rid = m.group(1)
    num_idx = int(rid[1:])
    
    num_matches = re.findall(r'(\d+\.?\d*)', line)
    if len(num_matches) < 5:
        return None
    
    try:
        atm = float(num_matches[-1])
        cln = float(num_matches[-2])
        srv = float(num_matches[-3])
        food = float(num_matches[-4])
        price = int(float(num_matches[-5]))
    except:
        return None
        
    text_part = re.sub(r'R\d{4}|\d+\.?\d*', '', line).strip()
    
    if num_idx in P1_MAPPINGS:
        province, cuisine = P1_MAPPINGS[num_idx]
    else:
        # direct province lookup
        province = "กรุงเทพมหานคร"
        for p in sorted(all_provinces, key=lambda x: -len(x)):
            if p in text_part:
                province = p
                break
        
        cuisine = "อาหารไทย"
        cuisine_keys = [
            ("อาหารญี่ปุ่น", ["ญี่ปุ่น", "ญี่", "ปุ่น"]),
            ("อาหารอิตาเลียน", ["อิตาเลียน", "อิตา", "เลีย"]),
            ("อาหารเกาหลี", ["เกาหลี", "เกา"]),
            ("อาหารอีสาน", ["อีสาน", "อีสา"]),
            ("อาหารนานาชาติ", ["นานาชาติ", "นานา"]),
            ("อาหารทะเล", ["ทะเล"]),
            ("อาหารฟิวชัน", ["ฟิวชัน", "ฟิว"]),
            ("คาเฟ่/เบเกอรี", ["คาเฟ่", "เบเกอ", "เบเกอรี่"]),
            ("อาหารจีน", ["จีน"]),
            ("อาหารไทย", ["ไทย"])
        ]
        for c_name, keys in cuisine_keys:
            if any(k in text_part for k in keys):
                cuisine = c_name
                break

    # Price range
    if "พรีเมียม" in text_part or "พรเีมยีม" in text_part:
        p_range = "พรีเมียม"
    elif "ประหยัด" in text_part or "ประหยดั" in text_part:
        p_range = "ประหยัด"
    elif "สูง" in text_part or "สงู" in text_part:
        p_range = "สูง"
    elif "ปานกลาง" in text_part:
        p_range = "ปานกลาง"
    else:
        if price <= 120:
            p_range = "ประหยัด"
        elif price <= 350:
            p_range = "ปานกลาง"
        elif price <= 700:
            p_range = "สูง"
        else:
            p_range = "พรีเมียม"

    return {
        "id": rid,
        "province": province,
        "cuisine": cuisine,
        "priceRange": p_range,
        "avgPrice": price,
        "foodQuality": round(food, 1),
        "serviceQuality": round(srv, 1),
        "cleanliness": round(cln, 1),
        "atmosphere": round(atm, 1)
    }

