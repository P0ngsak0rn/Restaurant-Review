def match_province_and_cuisine(text):
    # Notice: In the interleaved text, "ตัวอย่าง" (or "ตตัวอย่าง") and digits are mixed with province
    # If we filter out the letters 'ต', 'ั', 'ว', 'อ', 'ย', '่', 'า', 'ง', digits, spaces:
    # Let's see what remains!
    # Wait, some provinces also have 'ต', 'ั', etc.
    # Instead, we can check subsequence match!
    # In "ตตัวาอกยา่ ง", if we look for the characters of "ตาก" in order:
    # 'ต' -> index 0
    # 'า' -> index 5
    # 'ก' -> index 7
    # They appear as an ordered subsequence!
    
    # Let's test subsequence search:
    clean = text.replace(" ", "")
    
    # First, let's find cuisine:
    cuisine_found = "อาหารไทย"
    cuisine_chars = {
        "อาหารญี่ปุ่น": ["ญี่", "ปุ่น", "ญ"],
        "อาหารอิตาเลียน": ["อิตา", "เลีย", "อิต"],
        "อาหารเกาหลี": ["เกา", "หลี"],
        "อาหารอีสาน": ["อีสา", "สีาน", "อีส"],
        "อาหารนานาชาติ": ["นานา", "ชาติ"],
        "อาหารทะเล": ["ทะเล"],
        "อาหารฟิวชัน": ["ฟิว", "ชัน"],
        "คาเฟ่/เบเกอรี": ["คาเฟ่", "เบเกอ"],
        "อาหารจีน": ["จีน", "จนี"],
        "อาหารไทย": ["ไทย"]
    }
    for c_name, keys in cuisine_chars.items():
        if any(k in clean for k in keys):
            cuisine_found = c_name
            break
            
    # Now province:
    # Check each province by longest first:
    sorted_provs = sorted(all_provinces, key=lambda x: -len(x))
    best_p = None
    for p in sorted_provs:
        # Check if characters of p appear as a subsequence in clean
        it = iter(clean)
        if all(ch in it for ch in p):
            best_p = p
            break
            
    return best_p, cuisine_found

