def find_best_province(extracted):
    extracted_counts = Counter(extracted)
    best_p = None
    best_score = -100
    for p in all_provinces:
        p_counts = Counter(p)
        # overlap score
        matches = sum(min(extracted_counts[c], p_counts[c]) for c in p_counts)
        extra = sum(extracted_counts[c] for c in extracted_counts if c not in p_counts)
        missing = len(p) - matches
        score = matches * 3 - missing * 2 - extra
        if score > best_score:
            best_score = score
            best_p = p
    return best_p

