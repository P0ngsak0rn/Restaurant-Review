sample_tuayang = list("ตัวอย่าง")

def extract_province_chars(s):
    # remove spaces and digits
    s = "".join([c for c in s if not c.isdigit() and not c.isspace()])
    # remove characters of 'ตัวอย่าง'
    tuayang_counts = Counter("ตัวอย่าง")
    result = []
    for c in s:
        if tuayang_counts[c] > 0:
            tuayang_counts[c] -= 1
        else:
            result.append(c)
    return "".join(result)

