def clean_thai(t):
    # Remove "ตัวอย่าง \d+" or digits and "ร้านอาหาร"
    # Interleaved letters: notice "ตตัวาอกยา่ ง 0001" has characters from "ตัวอย่าง \d+" mixed with province
    # Let's count letter frequency or match against provinces
    cleaned = re.sub(r'[\s\d]', '', t)
    # find best province
    best_p = None
    best_score = 0
    for p in provinces:
        p_chars = set(p)
        score = sum(1 for c in p if c in cleaned)
        if score == len(p) or (len(p) > 4 and score >= len(p) - 1):
            if score > best_score:
                best_score = score
                best_p = p
    
    # find cuisine
    best_c = "อาหารไทย"
    for c in ["อาหารญี่ปุ่น", "อาหารอิตาเลียน", "อาหารเกาหลี", "อาหารอีสาน", "อาหารนานาชาติ", "อาหารทะเล", "อาหารฟิวชัน", "คาเฟ่/เบเกอรี", "คาเฟ่/เบเกอรี่", "อาหารจีน", "อาหารไทย"]:
        # check if key chars of cuisine appear
        c_core = c.replace("อาหาร", "").replace("คาเฟ่/", "")
        match_count = sum(1 for ch in c_core if ch in cleaned)
        if match_count >= len(c_core) - 1:
            best_c = "คาเฟ่/เบเกอรี" if "เบเกอ" in c else c
            break
            
    # price range
    p_range = "ปานกลาง"
    if "พรเีมยีม" in cleaned or "พรีเมียม" in cleaned:
        p_range = "พรีเมียม"
    elif "ประหยดั" in cleaned or "ประหยัด" in cleaned:
        p_range = "ประหยัด"
    elif "สงู" in cleaned or "สูง" in cleaned:
        p_range = "สูง"
    elif "ปานกลาง" in cleaned:
        p_range = "ปานกลาง"
        
    return best_p, best_c, p_range

for s in sample_texts:
    p, c, pr = clean_thai(s)
